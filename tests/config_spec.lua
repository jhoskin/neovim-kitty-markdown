local config = require('kitty-markdown.config')

describe('config', function()
  after_each(function()
    config.setup({})
  end)

  it('returns the README defaults', function()
    local c = config.setup({})
    assert.are.equal('tab', c.placement)
    assert.are.equal('auto', c.theme)
    assert.are.equal(100, c.text_width)
    assert.is_true(c.scroll_sync)
    assert.is_true(c.remote_images.enabled)
    assert.are.equal(10000, c.remote_images.timeout_ms)
    assert.are.equal(20 * 1024 * 1024, c.remote_images.max_bytes)
    assert.are.equal(vim.fn.stdpath('cache') .. '/kitty-markdown', c.cache.dir)
    assert.are.equal(500 * 1024 * 1024, c.cache.max_bytes)
    assert.is_nil(c.helper.path)
    assert.is_true(c.helper.download)
    assert.are.equal(30000, c.helper.request_timeout_ms)
    assert.are.equal('auto', c.mermaid.theme)
  end)

  it('merges nested user options without dropping siblings', function()
    local c = config.setup({ remote_images = { enabled = false }, placement = 'split' })
    assert.is_false(c.remote_images.enabled)
    assert.are.equal(10000, c.remote_images.timeout_ms)
    assert.are.equal('split', c.placement)
  end)

  it('does not mutate the defaults', function()
    config.setup({ text_width = 60 })
    assert.are.equal(100, config.defaults.text_width)
  end)

  it('rejects an unknown placement', function()
    assert.has_error(function()
      config.setup({ placement = 'window' })
    end, 'invalid placement')
  end)

  it('rejects an unknown theme', function()
    assert.has_error(function()
      config.setup({ theme = 'solarized' })
    end, 'invalid theme')
  end)

  it('rejects an unknown mermaid theme', function()
    assert.has_error(function()
      config.setup({ mermaid = { theme = 'neo' } })
    end, 'invalid mermaid.theme')
  end)

  it('rejects a non-positive text width', function()
    assert.has_error(function()
      config.setup({ text_width = 0 })
    end, 'invalid text_width')
  end)

  it('get returns the current table', function()
    local c = config.setup({ text_width = 72 })
    assert.are.equal(c, config.get())
    assert.are.equal(72, config.get().text_width)
  end)
end)
