//! The subsets of the page's Open Sans web font.
//!
//! mermaid-cli loads Open Sans from `@fontsource/open-sans` 5.3.0, whose
//! `400.css` declares ten `@font-face` rules, one subset file each, with a
//! `unicode-range`. Blink treats them as one segmented face: a subset is
//! tried only for text with a character in its declared range, and it
//! shapes only the characters that are both declared and in its own
//! `cmap` (`HarfBuzzFace` hides the rest behind the range set). The
//! bundled TTF draws every glyph of every subset, but also characters no
//! subset has (`―`, `‰`, `˘`), which Chrome takes from the next family.
//! The italic subsets cover the same characters. The table comes from
//! the subset files with fontTools; DECISIONS.md says how to regenerate it.

/// One `@font-face` rule: its declared `unicode-range` and the characters
/// it can draw, as inclusive code point ranges in ascending order.
pub struct Subset {
    pub declared: &'static [(u32, u32)],
    pub drawn: &'static [(u32, u32)],
}

fn in_ranges(ranges: &[(u32, u32)], ch: char) -> bool {
    let cp = u32::from(ch);
    ranges
        .binary_search_by(|&(start, end)| {
            if end < cp {
                std::cmp::Ordering::Less
            } else if start > cp {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

impl Subset {
    pub fn declares(&self, ch: char) -> bool {
        in_ranges(self.declared, ch)
    }

    pub fn draws(&self, ch: char) -> bool {
        in_ranges(self.drawn, ch)
    }
}

/// True when some subset declares `ch`: Blink's `RangeSetContributesForHint`
/// for the segmented face.
pub fn declares(ch: char) -> bool {
    SUBSETS.iter().any(|s| s.declares(ch))
}

